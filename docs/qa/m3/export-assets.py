"""Export the live-background sprites to WebP (1x + 2x) and write src/live-bg/sprites.ts.
Run from the repo root:  python3 docs/qa/m3/export-assets.py
Ahmad poses come from assets/ahmad/src-*.png (1254², alpha noise below 9 is trimmed),
the run cycle from ahmad-run-cycle-6f.png (no src exists for it), the channel marks from assets/channels.
Anchors (feet) follow the reference prototype: ax/ay as a fraction of the cropped pose."""
import os, subprocess, json
from PIL import Image
H = 'docs/handoff/farq-live-background/assets'
OUT = 'src/assets/live-bg'
os.makedirs(OUT, exist_ok=True)
BASE = 0.32  # prototype: css px per stored px (stored poses are ~219 px tall)
# group -> [(src file, prototype stored w, h, ax, ay)]
POSES = {
  'NE': [('src-run-NE', 142, 218, 77.8, 217.6)],
  'NW': [('src-run-NW', 175, 219, 78.3, 218.9)],
  'S': [('src-run-S', 153, 221, 82.1, 221.0)],
  'tiredF': [('src-tired-front-1', 95, 215, 47.6, 215.5), ('src-tired-front-2', 106, 219, 53.2, 219.1), ('src-tired-front-3', 99, 215, 49.6, 215.5)],
  'tiredR': [('src-tired-right-1', 114, 215, 49.8, 215.5), ('src-tired-right-2', 118, 216, 51.6, 216.0)],
  'tiredL': [('src-tired-left-1', 120, 212, 67.5, 212.0), ('src-tired-left-2', 108, 215, 56.9, 214.9)],
  'present': [('src-present', 105, 222, 48.2, 222.1)],
}
GMUL = {'tiredF': .95, 'tiredR': .95, 'tiredL': .95, 'present': 1.04}

def webp(im, path):
  tmp = path + '.png'; im.save(tmp)
  subprocess.run(['cwebp', '-quiet', '-q', '82', '-alpha_q', '90', '-exact', tmp, '-o', path], check=True); os.remove(tmp)

def crop(path):
  im = Image.open(path).convert('RGBA')
  bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
  return im.crop(bb)

manifest = {}
for g, frames in POSES.items():
  manifest[g] = []
  for i, (name, w, h, ax, ay) in enumerate(frames):
    im = crop(f'{H}/ahmad/{name}.png')
    ratio_src, ratio_ref = im.width / im.height, w / h
    assert abs(ratio_src - ratio_ref) < .06, (name, ratio_src, ratio_ref)
    m = BASE * GMUL.get(g, 1)
    cw, ch = w * m, h * m  # css size
    stem = f'ahmad-{g}-{i}'
    for s in (1, 2):
      webp(im.resize((round(cw * s), round(ch * s)), Image.LANCZOS), f'{OUT}/{stem}@{s}x.webp')
    manifest[g].append({'f': stem, 'w': round(cw, 2), 'h': round(ch, 2), 'ax': round(ax * m, 2), 'ay': round(ay * m, 2)})

# run cycle: 6 frames of 182x230, drawn 70 px tall
cyc = Image.open(f'{H}/ahmad/ahmad-run-cycle-6f.png').convert('RGBA')
CH = 70; cw = 182 * CH / 230
for s in (1, 2):
  fw, fh = round(cw * s), round(CH * s)
  sheet = Image.new('RGBA', (fw * 6, fh))
  for k in range(6):
    sheet.paste(cyc.crop((k * 182, 0, k * 182 + 182, 230)).resize((fw, fh), Image.LANCZOS), (k * fw, 0))
  webp(sheet, f'{OUT}/ahmad-cycle@{s}x.webp')
manifest['cycle'] = {'f': 'ahmad-cycle', 'w': round(cw, 2), 'h': CH, 'n': 6}

for c in ('whatsapp', 'call', 'sms', 'haraj', 'mail'):
  im = Image.open(f'{H}/channels/channel-{c}.png').convert('RGBA')
  for s in (1, 2):
    webp(im.resize((20 * s, 20 * s), Image.LANCZOS), f'{OUT}/channel-{c}@{s}x.webp')

# sprites.ts — URLs go through Vite's asset pipeline (hashed files, never inlined: see assetsInlineLimit note in README)
lines = ['// Generated by docs/qa/m3/export-assets.py — do not edit by hand.',
         '// Sizes and foot anchors are in CSS px; every file exists at @1x and @2x.', '']
files = sorted(f[:-8] for f in os.listdir(OUT) if f.endswith('@1x.webp'))
lines.append('const URLS = import.meta.glob<string>(\'../assets/live-bg/*.webp\', { eager: true, import: \'default\', query: \'?no-inline\' })')
lines.append('export const url = (stem: string, scale: 1 | 2): string => URLS[`../assets/live-bg/${stem}@${scale}x.webp`]')
lines.append('')
lines.append('export type Pose = { f: string; w: number; h: number; ax: number; ay: number }')
poses = {k: v for k, v in manifest.items() if k != 'cycle'}
lines.append('export const POSES: Record<string, Pose[]> = ' + json.dumps(poses).replace('"f"', 'f').replace('"w"', 'w').replace('"h"', 'h').replace('"ax"', 'ax').replace('"ay"', 'ay'))
lines.append('export const CYCLE = ' + json.dumps(manifest['cycle']).replace('"f"', 'f').replace('"w"', 'w').replace('"h"', 'h').replace('"n"', 'n'))
lines.append("export const CHANNELS = ['whatsapp', 'call', 'sms', 'haraj', 'mail'] as const")
open('src/live-bg/sprites.ts', 'w').write('\n'.join(lines) + '\n')
print('ok', len(files), 'stems'); print(sum(os.path.getsize(f'{OUT}/{f}') for f in os.listdir(OUT)), 'bytes')
