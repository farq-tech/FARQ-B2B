import fs from 'node:fs'
import ts from 'typescript'
const source = fs.readFileSync('src/live-bg/webMesh.ts', 'utf8')
if (/^\s*import /m.test(source)) throw new Error('Shared mesh must remain standalone for the gate')
const shared = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText.replace(/^export /gm, '')
fs.writeFileSync('public/gate-network.js', `// Generated by scripts/sync-gate-network.mjs from src/live-bg/webMesh.ts.
(() => {
${shared}
const canvas=document.createElement('canvas'), staticCanvas=document.createElement('canvas');
canvas.setAttribute('aria-hidden','true');canvas.style.cssText='position:fixed;inset:0;width:100%;height:100%;pointer-events:none;z-index:0';document.body.prepend(canvas);
const form=document.querySelector('form');form.style.position='relative';form.style.zIndex='1';form.style.boxSizing='border-box';form.style.width='min(360px,calc(100vw - 32px))';form.style.minWidth='0';
const ctx=canvas.getContext('2d'), bg=staticCanvas.getContext('2d'), mq=matchMedia('(prefers-reduced-motion: reduce)');let points=[],edges=[],raf=0,w=0,h=0,dpr=1;
function build(){
 w=innerWidth;h=innerHeight;dpr=Math.min(2,devicePixelRatio||1);canvas.width=staticCanvas.width=Math.round(w*dpr);canvas.height=staticCanvas.height=Math.round(h*dpr);
 const mesh=webMesh(w,h),rect=form.getBoundingClientRect();points=mesh.points;
 edges=mesh.edges.filter(e=>{const a=points[e.a],b=points[e.b],steps=Math.ceil(e.L/6);for(let i=0;i<=steps;i++){const x=a.x+(b.x-a.x)*i/steps,y=a.y+(b.y-a.y)*i/steps;if(x>rect.left-22&&x<rect.right+22&&y>rect.top-22&&y<rect.bottom+22)return false}return true});
 bg.setTransform(dpr,0,0,dpr,0,0);bg.clearRect(0,0,w,h);bg.strokeStyle=WEB_INK.line;bg.lineWidth=.9;bg.beginPath();for(const e of edges){const a=points[e.a],b=points[e.b];bg.moveTo(a.x,a.y);bg.lineTo(b.x,b.y)}bg.stroke();run()
}
function draw(now){ctx.setTransform(dpr,0,0,dpr,0,0);ctx.clearRect(0,0,w,h);ctx.drawImage(staticCanvas,0,0,w,h);if(mq.matches)return;drawWebExpansion(ctx,points,edges,now/1000,WEB_INK.go,WEB_INK.back,0,h);raf=requestAnimationFrame(draw)}
function run(){cancelAnimationFrame(raf);if(!document.hidden)draw(performance.now())}
addEventListener('resize',build);document.addEventListener('visibilitychange',run);mq.addEventListener('change',run);build();
})();
`)
