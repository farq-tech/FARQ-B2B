_TABLE_YEARS = (2024, 2043)  # every Ramadan in these Gregorian years is in the table


def now_utc():
    """The one clock the send rule reads (tests patch this)."""
    return datetime.now(UTC)


def is_ramadan(d):
    """Whether Saudi calendar day `d` is in Ramadan: the Umm al-Qura table, else (outside 2024-2043) month 9 of the
    arithmetic (tabular, civil-epoch) Islamic calendar, which can differ from Umm al-Qura by a day or two."""
    if _TABLE_YEARS[0] <= d.year <= _TABLE_YEARS[1]:
        return any(a <= d <= b for a, b in _RAMADAN)
    jd = d.toordinal() + 1721424.5  # Julian day at 00:00 UTC
    epoch = 1948439.5
    year = math.floor((30 * (jd - epoch) + 10646) / 10631)
    start = lambda y, m: 1 + math.ceil(29.5 * (m - 1)) + (y - 1) * 354 + math.floor((3 + 11 * y) / 30) + epoch - 1
    month = min(12, math.ceil((jd - (29 + start(year, 1))) / 29.5) + 1)
    return month == 9


# ---- adhan's astronomy (Astronomical.js, SolarCoordinates.js, SolarTime.js), line for line ----
_rad, _deg = (lambda x: x * math.pi / 180.0), (lambda x: x * 180.0 / math.pi)
def _scale(n, mx): return n - mx * math.floor(n / mx)
def _unwind(a): return _scale(a, 360.0)
def _qshift(a): return a if -180 <= a <= 180 else a - 360 * math.floor(a / 360 + 0.5)  # JS Math.round


def _julian_day(y, m, d, hours=0):
    Y = y if m > 2 else y - 1
    M = m if m > 2 else m + 12
    D = d + hours / 24
    A = math.trunc(Y / 100)
    B = math.trunc(2 - A + math.trunc(A / 4))
    return math.trunc(365.25 * (Y + 4716)) + math.trunc(30.6001 * (M + 1)) + D + B - 1524.5


def _interp(y2, y1, y3, n):
    a, b = y2 - y1, y3 - y2
    return y2 + n / 2 * (a + b + n * (b - a))


def _interp_angles(y2, y1, y3, n):
    a, b = _unwind(y2 - y1), _unwind(y3 - y2)
    return y2 + n / 2 * (a + b + n * (b - a))


class _Solar:
    def __init__(self, jd):
        T = (jd - 2451545.0) / 36525
        L0 = _unwind(280.4664567 + 36000.76983 * T + 0.0003032 * T ** 2)
        Lp = _unwind(218.3165 + 481267.8813 * T)
        Om = _unwind(125.04452 - 1934.136261 * T + 0.0020708 * T ** 2 + T ** 3 / 450000)
        M = _unwind(357.52911 + 35999.05029 * T - 0.0001537 * T ** 2)
        Mr = _rad(M)
        C = (1.914602 - 0.004817 * T - 0.000014 * T ** 2) * math.sin(Mr) + (0.019993 - 0.000101 * T) * math.sin(2 * Mr) + 0.000289 * math.sin(3 * Mr)
        lam = _unwind(L0 + C - 0.00569 - 0.00478 * math.sin(_rad(125.04 - 1934.136 * T)))
        Lam = _rad(lam)
        JD = T * 36525 + 2451545.0
        Th0 = _unwind(280.46061837 + 360.98564736629 * (JD - 2451545) + 0.000387933 * T ** 2 - T ** 3 / 38710000)
        dPsi = -17.2 / 3600 * math.sin(_rad(Om)) - 1.32 / 3600 * math.sin(2 * _rad(L0)) - 0.23 / 3600 * math.sin(2 * _rad(Lp)) + 0.21 / 3600 * math.sin(2 * _rad(Om))
        dEps = 9.2 / 3600 * math.cos(_rad(Om)) + 0.57 / 3600 * math.cos(2 * _rad(L0)) + 0.1 / 3600 * math.cos(2 * _rad(Lp)) - 0.09 / 3600 * math.cos(2 * _rad(Om))
        Eps0 = 23.439291 - 0.013004167 * T - 0.0000001639 * T ** 2 + 0.0000005036 * T ** 3
        EpsApp = _rad(Eps0 + 0.00256 * math.cos(_rad(125.04 - 1934.136 * T)))
        self.declination = _deg(math.asin(math.sin(EpsApp) * math.sin(Lam)))
        self.right_ascension = _unwind(_deg(math.atan2(math.cos(EpsApp) * math.sin(Lam), math.cos(Lam))))
        self.sidereal = Th0 + dPsi * 3600 * math.cos(_rad(Eps0 + dEps)) / 3600


class _SolarTime:
    def __init__(self, d, lat, lon):
        jd = _julian_day(d.year, d.month, d.day, 0)
        self.lat, self.lon = lat, lon
        s, p, n = _Solar(jd), _Solar(jd - 1), _Solar(jd + 1)
        self.s, self.p, self.n = s, p, n
        self.m0 = _scale((s.right_ascension + (-lon) - s.sidereal) / 360, 1)
        Th = _unwind(s.sidereal + 360.985647 * self.m0)
        a = _unwind(_interp_angles(s.right_ascension, p.right_ascension, n.right_ascension, self.m0))
        H = _qshift(Th - (-lon) - a)
        self.transit = (self.m0 + H / -360) * 24
        self.sunrise = self.hour_angle(-50.0 / 60.0, False)
        self.sunset = self.hour_angle(-50.0 / 60.0, True)

    def hour_angle(self, h0, after):
        s, p, n, lat, Lw = self.s, self.p, self.n, self.lat, -self.lon
        t1 = math.sin(_rad(h0)) - math.sin(_rad(lat)) * math.sin(_rad(s.declination))
        t2 = math.cos(_rad(lat)) * math.cos(_rad(s.declination))
        H0 = _deg(math.acos(t1 / t2))
        m = self.m0 + H0 / 360 if after else self.m0 - H0 / 360
        Th = _unwind(s.sidereal + 360.985647 * m)
        a = _unwind(_interp_angles(s.right_ascension, p.right_ascension, n.right_ascension, m))
        delta = _interp(s.declination, p.declination, n.declination, m)
        H = Th - Lw - a
        h = _deg(math.asin(math.sin(_rad(lat)) * math.sin(_rad(delta)) + math.cos(_rad(lat)) * math.cos(_rad(delta)) * math.cos(_rad(H))))
        dm = (h - h0) / (360 * math.cos(_rad(delta)) * math.cos(_rad(lat)) * math.sin(_rad(H)))
        return (m + dm) * 24

    def afternoon(self, shadow):
        inv = shadow + math.tan(_rad(abs(self.lat - self.s.declination)))
        return self.hour_angle(_deg(math.atan(1.0 / inv)), True)


def _utc_at(d, hours):
    """adhan's TimeComponents(hours).utcDate(y, m, d): whole seconds, truncated."""
    hh = math.floor(hours)
    mm = math.floor((hours - hh) * 60)
    ss = math.floor((hours - (hh + mm / 60)) * 60 * 60)
    return datetime(d.year, d.month, d.day, tzinfo=UTC) + timedelta(hours=hh, minutes=mm, seconds=ss)


def _round_minute(t):
    s = t.second
    return t + timedelta(seconds=(60 - s) if s >= 30 else -s)


def prayer_times(date_ksa, lat, lon):
    """The five prayers (and sunrise) of Saudi calendar day `date_ksa` at (lat, lon), as aware UTC datetimes."""
    d = date_ksa.date() if isinstance(date_ksa, datetime) else date_ksa
    st = _SolarTime(d, lat, lon)
    sunrise, sunset = _utc_at(d, st.sunrise), _utc_at(d, st.sunset)
    tomorrow = d + timedelta(days=1)
    night = (_utc_at(tomorrow, _SolarTime(tomorrow, lat, lon).sunrise) - sunset).total_seconds()
    fajr = _utc_at(d, st.hour_angle(-18.5, False))
    safe_fajr = sunrise - timedelta(seconds=night / 2)  # HighLatitudeRule.MiddleOfTheNight
    if safe_fajr > fajr: fajr = safe_fajr
    ramadan = is_ramadan(d)
    out = {'fajr': _round_minute(fajr), 'sunrise': _round_minute(sunrise), 'dhuhr': _round_minute(_utc_at(d, st.transit)),
           'asr': _round_minute(_utc_at(d, st.afternoon(1))), 'maghrib': _round_minute(sunset),
           'isha': _round_minute(sunset + timedelta(minutes=90)), 'ramadan': ramadan}
    if ramadan: out['isha'] = out['maghrib'] + timedelta(minutes=120)
    return out


def _ksa_day(dt): return dt.astimezone(KSA).date()


def quiet_windows(dt_utc, lat, lon):
    """[(prayer, from, to)] of the Saudi day containing dt_utc, sorted: each prayer + 25 min; Friday 11:30-13:30."""
    d = _ksa_day(dt_utc)
    p = prayer_times(d, lat, lon)
    ws = [(k, p[k], p[k] + timedelta(minutes=WINDOW_MIN)) for k in PRAYERS]
    if d.weekday() == 4:  # Friday: jumuah replaces dhuhr (union of the two)
        f = datetime(d.year, d.month, d.day, *FRIDAY_FROM, tzinfo=KSA).astimezone(UTC)
        t = datetime(d.year, d.month, d.day, *FRIDAY_TO, tzinfo=KSA).astimezone(UTC)
        ws = [('jumuah', min(a, f), max(b, t)) if k == 'dhuhr' else (k, a, b) for k, a, b in ws]
    return sorted(ws, key=lambda w: w[1])


def quiet_window_at(dt_utc, lat, lon):
    """The (prayer, from, to) window dt_utc falls in, or None."""
    return next((w for w in quiet_windows(dt_utc, lat, lon) if w[1] <= dt_utc < w[2]), None)


def next_allowed(dt_utc, lat, lon):
    """The first moment from dt_utc on outside every quiet window."""
    t = dt_utc
    for _ in range(6):
        w = quiet_window_at(t, lat, lon)
        if not w: return t
        t = w[2]
    return t


def ksa_clock(dt):
    """'1:05 م' -- Saudi clock, 12-hour, Latin digits, like the front end's ksaClock."""
    k = dt.astimezone(KSA)
    return f"{(k.hour + 11) % 12 + 1}:{k.minute:02d} {'ص' if k.hour < 12 else 'م'}"


def city_coords(name):
    """(lat, lon) for a City.en / Arabic / alias name; unknown or missing -> Riyadh."""
    k = ' '.join(str(name or '').strip().lower().replace('-', ' ').replace('_', ' ').split())
    return CITIES.get(ALIASES.get(k, k), CITIES['riyadh'])


def _iso(dt): return dt.astimezone(UTC).strftime('%Y-%m-%dT%H:%M:%S.') + f'{dt.microsecond // 1000:03d}Z'


def block_for_cities(city_names, now_utc=None):
    """The 409 payload if a send now would fall in a prayer window in any of the cities, else None."""
    now = now_utc or globals()['now_utc']()
    coords = list(dict.fromkeys(city_coords(c) for c in (city_names or []))) or [CITIES['riyadh']]
    hit = next((w for w in (quiet_window_at(now, *c) for c in coords) if w), None)
    if not hit: return None
    t = now
    for _ in range(12):  # later than every city's window
        nxt = max(next_allowed(t, *c) for c in coords)
        if nxt == t: break
        t = nxt
    clock = ksa_clock(t)
    return {'ok': False, 'error': 'PRAYER_WINDOW', 'prayer': hit[0],
            'message_ar': f'الحين وقت صلاة {PRAYER_AR[hit[0]]}، فما أرسلنا الحملة. تقدر ترسلها من الساعة {clock}.',
            'next_allowed': _iso(t), 'next_allowed_ar': clock}


def block_for_body(body, now_utc=None):
    """block_for_cities for a /send-farq request body: the distinct targets[].city; unreadable body -> Riyadh."""
    try:
        targets = json.loads(body or b'{}').get('targets') or []
        cities = [t.get('city') for t in targets if isinstance(t, dict)]
    except Exception: cities = []
    return block_for_cities(cities, now_utc)
