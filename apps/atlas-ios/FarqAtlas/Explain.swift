/// A figure that explains itself on tap.
struct Explained<Label: View>: View {
    let title: String
    let lines: [String]
    @ViewBuilder let label: () -> Label
    @State private var open = false

    var body: some View {
        Button { open = true } label: { label().contentShape(.rect) }
            .buttonStyle(.plain)
            .popover(isPresented: $open, attachmentAnchor: .rect(.bounds), arrowEdge: .top) {
                VStack(alignment: .leading, spacing: 8) {
                    Text("كيف حُسب: \(title)").font(Typo.headline)
                    ForEach(lines, id: \.self) { Text($0).font(Typo.subheadline).fixedSize(horizontal: false, vertical: true) }
                }
                .padding()
                .frame(idealWidth: 300, maxWidth: 320)
                .presentationCompactAdaptation(.popover)
                .environment(\.layoutDirection, .rightToLeft)
            }
            .accessibilityHint("اضغط لمعرفة كيف حُسب")
    }
}
